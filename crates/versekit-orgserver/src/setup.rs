//! Secure by default: the admin password the server makes for itself, HTTPS as the proxy in front reports it, and
//! the self-check of password, HTTPS, the data folder, the clock and the version. Its findings show in full only in
//! the administration; the public status page says no more than "setup incomplete".

use std::path::{Path, PathBuf};

use ring::rand::{SecureRandom, SystemRandom};

use crate::http::Request;
use crate::{Server, hash};

/// The file in the data folder that holds the generated admin password.
pub const PASSWORD_FILE: &str = "admin-password.txt";
/// 2026-11-01 00:00 UTC: a clock before it is wrong.
pub const CLOCK_FLOOR: u64 = 1_793_491_200;
/// Letters of a generated password: no 0/O, 1/l/I.
const ALPHABET: &[u8] = b"abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789";
const PASSWORD_LETTERS: usize = 24;

/// Where the admin password comes from.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum AdminSource {
    /// None set (a server built in code, as in tests).
    #[default]
    None,
    /// `VERSEKIT_ORG_ADMIN_PASSWORD` or `VERSEKIT_ORG_ADMIN_PASSWORD_FILE`.
    Environment,
    /// Generated by the server into this file.
    File(PathBuf),
    /// Turned off on purpose with `VERSEKIT_ORG_ADMIN=off`.
    Off,
}

fn generate() -> Result<String, String> {
    let rng = SystemRandom::new();
    let mut letters = String::new();
    while letters.chars().filter(|c| *c != '-').count() < PASSWORD_LETTERS {
        let mut byte = [0u8; 1];
        rng.fill(&mut byte).map_err(|_| "the system gives no random numbers".to_string())?;
        // 216 is the largest multiple of 54 below 256: no letter comes up more often.
        if byte[0] < 216 {
            if !letters.is_empty() && letters.chars().filter(|c| *c != '-').count() % 6 == 0 {
                letters.push('-');
            }
            letters.push(ALPHABET[usize::from(byte[0]) % ALPHABET.len()] as char);
        }
    }
    Ok(letters)
}

/// Whether others than the owner may read or write `path`; always false where the system has no such rights.
pub fn too_open(path: &Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(path).is_ok_and(|m| m.permissions().mode() & 0o077 != 0)
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        false
    }
}

/// Gives `path` to the owner alone.
pub fn make_private(path: &Path) -> std::io::Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        Ok(())
    }
}

/// Writes `text` into a new file that only the owner may read.
fn write_private(path: &Path, text: &str) -> std::io::Result<()> {
    use std::io::Write;
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options.open(path)?;
    file.write_all(text.as_bytes())?;
    file.write_all(b"\n")?;
    file.sync_all()
}

/// The admin password of the data folder `dir`: read from `admin-password.txt`, or made and written there on the
/// first start. `true` when it was made now. A file others may read is closed to the owner.
pub fn admin_password(dir: &Path) -> Result<(String, bool), String> {
    let file = dir.join(PASSWORD_FILE);
    match std::fs::read_to_string(&file) {
        Ok(text) => {
            let password = text.trim().to_string();
            if password.chars().count() < crate::admin::MIN_PASSWORD {
                return Err(format!("{} holds no password of at least {} characters", file.display(), crate::admin::MIN_PASSWORD));
            }
            if too_open(&file) {
                make_private(&file).map_err(|e| format!("{} is readable by others and cannot be closed: {e}", file.display()))?;
            }
            Ok((password, false))
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            let password = generate()?;
            write_private(&file, &password).map_err(|e| format!("cannot write {}: {e}", file.display()))?;
            Ok((password, true))
        }
        Err(error) => Err(format!("cannot read {}: {error}", file.display())),
    }
}

/// Whether the proxy in front says the request came over HTTPS: `X-Forwarded-Proto: https`, `Forwarded: proto=https`
/// or `X-Forwarded-Ssl: on`. Of a list the last entry counts, the one the proxy next to the server added. This finds
/// a wrong setup; it is no protection on its own, which is why the port stays on 127.0.0.1 or inside the compose
/// network.
pub fn forwarded_https(request: &Request) -> bool {
    let proto = request.header("X-Forwarded-Proto").and_then(|v| v.rsplit(',').next()).map(str::trim);
    if let Some(proto) = proto {
        return proto.eq_ignore_ascii_case("https");
    }
    if let Some(forwarded) = request.header("Forwarded") {
        let last = forwarded.rsplit(',').next().unwrap_or_default();
        return last.split(';').filter_map(|p| p.trim().split_once('=')).any(|(k, v)| {
            k.trim().eq_ignore_ascii_case("proto") && v.trim().trim_matches('"').eq_ignore_ascii_case("https")
        });
    }
    request.header("X-Forwarded-Ssl").is_some_and(|v| v.trim().eq_ignore_ascii_case("on"))
}

/// Whether a folder takes new files: a probe file is written and removed.
pub fn writable(dir: &Path) -> bool {
    let probe = dir.join(format!(".versekit-probe-{}", &hash(&format!("{:?}", std::time::SystemTime::now()))[..12]));
    let done = std::fs::write(&probe, b"").is_ok();
    let _ = std::fs::remove_file(&probe);
    done
}

/// One point of the self-check.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Finding {
    pub ok: bool,
    /// Whether a fault here makes the public status page say "setup incomplete".
    pub public: bool,
    pub de: String,
    pub en: String,
}

fn finding(ok: bool, public: bool, de: impl Into<String>, en: impl Into<String>) -> Finding {
    Finding { ok, public, de: de.into(), en: en.into() }
}

/// The self-check at the time `now`.
pub fn findings(server: &Server, now: u64) -> Vec<Finding> {
    let config = server.config();
    let mut list = Vec::new();
    list.push(match &config.admin_source {
        AdminSource::Environment => finding(true, true, "Admin-Passwort aus der Umgebung gesetzt", "Admin password set through the environment"),
        AdminSource::File(path) if too_open(path) => finding(
            false,
            true,
            format!("{} ist für andere lesbar", path.display()),
            format!("{} is readable by others", path.display()),
        ),
        AdminSource::File(path) => finding(
            true,
            true,
            format!("Admin-Passwort selbst erzeugt, liegt nur für den Besitzer lesbar in {}", path.display()),
            format!("Admin password generated, kept readable for the owner only in {}", path.display()),
        ),
        AdminSource::Off => finding(false, false, "Verwaltung ausgeschaltet (VERSEKIT_ORG_ADMIN=off)", "Administration turned off (VERSEKIT_ORG_ADMIN=off)"),
        AdminSource::None => finding(false, false, "Kein Admin-Passwort", "No admin password"),
    });
    let refused = server.refused_plain();
    list.push(if config.test_mode {
        finding(
            false,
            false,
            "Testbetrieb ohne HTTPS: nur zum Ausprobieren, nicht für echte Mitglieder",
            "Test mode without HTTPS: for trying out only, not for real members",
        )
    } else if refused > 0 {
        finding(
            false,
            true,
            format!("{refused} Anfragen ohne HTTPS abgewiesen: Liegt der Reverse-Proxy davor und setzt er X-Forwarded-Proto?"),
            format!("{refused} requests without HTTPS refused: is the reverse proxy in front, and does it set X-Forwarded-Proto?"),
        )
    } else {
        finding(true, true, "Nur über HTTPS erreichbar (Reverse-Proxy erkannt)", "Reachable over HTTPS only (reverse proxy recognised)")
    });
    if let Some(file) = &config.state_file {
        let dir = file.parent().filter(|d| !d.as_os_str().is_empty()).unwrap_or(Path::new("."));
        list.push(if !server.data_writable() {
            finding(false, true, format!("{} ist nicht beschreibbar", dir.display()), format!("{} is not writable", dir.display()))
        } else if too_open(file) {
            finding(false, true, format!("{} ist für andere lesbar", file.display()), format!("{} is readable by others", file.display()))
        } else {
            finding(true, true, format!("Datenordner {} beschreibbar und geschlossen", dir.display()), format!("Data folder {} writable and closed", dir.display()))
        });
    }
    let saved = server.last_saved();
    list.push(if now < CLOCK_FLOOR {
        finding(false, true, "Die Uhr des Rechners geht falsch (vor November 2026)", "The clock of the host is wrong (before November 2026)")
    } else if saved > now + 86_400 {
        finding(false, true, "Die Uhr ging zurück: Der Zustand wurde zuletzt in der Zukunft gespeichert", "The clock went back: the state was last saved in the future")
    } else {
        finding(true, true, "Uhr plausibel", "Clock plausible")
    });
    list.push(match &config.discord {
        None => finding(true, false, "Mitglieder-Portal aus (keine Discord-Einstellungen)", "Members' portal off (no Discord settings)"),
        Some(_) if server.portal_unmapped() => finding(
            false,
            false,
            "Mitglieder-Portal an, aber keine Discord-Rolle zugeordnet: Jede Anmeldung wartet, bis die Leitung sie unter Zugang freischaltet",
            "Members' portal on, but no Discord role mapped: every login waits until the lead lets it in under Access",
        ),
        Some(discord) => finding(
            true,
            false,
            format!("Mitglieder-Portal an (Discord-Server {})", discord.guild_id),
            format!("Members' portal on (Discord server {})", discord.guild_id),
        ),
    });
    if config.discord.is_some() && config.test_mode {
        list.push(finding(
            false,
            false,
            "Portal im Testbetrieb: Die Anmeldung läuft ohne HTTPS, nur zum Ausprobieren",
            "Portal in test mode: the login runs without HTTPS, for trying out only",
        ));
    }
    let own = env!("CARGO_PKG_VERSION");
    let update = server.update_state();
    list.push(match (&update.offer, config.update_check) {
        (Some(offer), _) => finding(
            false,
            false,
            format!("Version {own}, Update verfügbar: {}", offer.version),
            format!("Version {own}, update available: {}", offer.version),
        ),
        (None, false) => finding(true, false, format!("Version {own}, Update-Abfrage ausgeschaltet"), format!("Version {own}, update check turned off")),
        (None, true) if update.checked == 0 => finding(true, false, format!("Version {own}, noch nicht nach Updates gefragt"), format!("Version {own}, not asked for updates yet")),
        (None, true) => finding(true, false, format!("Version {own} ist aktuell"), format!("Version {own} is up to date")),
    });
    list
}

/// Whether the public status page says "setup incomplete".
pub fn incomplete(server: &Server, now: u64) -> bool {
    findings(server, now).iter().any(|f| f.public && !f.ok)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_generated_password_is_long_random_and_stays() {
        let dir = std::env::temp_dir().join(format!("versekit-orgserver-setup-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let (first, made) = admin_password(&dir).unwrap();
        assert!(made);
        assert_eq!(first.chars().filter(|c| *c != '-').count(), PASSWORD_LETTERS);
        assert!(first.chars().all(|c| c == '-' || ALPHABET.contains(&(c as u8))), "{first}");
        assert!(!too_open(&dir.join(PASSWORD_FILE)), "only the owner reads it");
        let (again, made) = admin_password(&dir).unwrap();
        assert_eq!((again.as_str(), made), (first.as_str(), false), "the second start reads the same");
        assert_ne!(generate().unwrap(), first);
        std::fs::write(dir.join(PASSWORD_FILE), "kurz").unwrap();
        assert!(admin_password(&dir).unwrap_err().contains("at least"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn https_is_read_from_the_headers_of_the_proxy() {
        let with = |headers: &[(&str, &str)]| forwarded_https(&Request::new("GET", "/", headers, b""));
        assert!(with(&[("X-Forwarded-Proto", "https")]));
        assert!(with(&[("X-Forwarded-Proto", "http, HTTPS")]), "the entry of the proxy next to the server counts");
        assert!(!with(&[("X-Forwarded-Proto", "https, http")]), "an entry the client wrote first does not");
        assert!(!with(&[("X-Forwarded-Proto", "http")]));
        assert!(with(&[("Forwarded", "for=1.2.3.4;proto=https;host=orga.example.org")]));
        assert!(!with(&[("Forwarded", "for=1.2.3.4;proto=http")]));
        assert!(with(&[("X-Forwarded-Ssl", "on")]));
        assert!(!with(&[]));
    }
}
