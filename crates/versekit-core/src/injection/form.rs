//! How an addition looks in a `global.ini` line, how it is found again and
//! how it is cut out: the patterns of `injection.py`.
//!
//! Every pattern is the Python one, character for character; `\s` is
//! written as [`PY_SPACE`] because Rust's `\s` does not know `\x1c` to
//! `\x1f`. The patterns and headings are game file content, not interface
//! texts: they must match what earlier versions and other tools wrote.

use std::sync::LazyLock;

use regex::Regex;

use crate::text::{PY_SPACE, py_rstrip};

/// The old marks around an addition (`injection.OPEN`, `CLOSE`).
pub const OPEN: &str = "[SCBPW]";
pub const CLOSE: &str = "[/SCBPW]";

/// The headings that tell a block as ours or as one from the same source.
pub const HEADINGS: [&str; 8] = [
    "BAUPLÄNE AUS DIESEM AUFTRAG",
    "BLUEPRINTS FROM THIS CONTRACT",
    "MÖGLICHE BAUPLÄNE FÜR DIESEN MISSIONSTYP",
    "POSSIBLE BLUEPRINTS FOR THIS MISSION TYPE",
    "<EM4>Dieser Missionstyp wird vom Spiel dynamisch erzeugt",
    "<EM4>This mission type is dynamically generated by the game",
    "VERSE-KIT: BAUPLAN & HERSTELLUNG",
    "VERSE-KIT: BLUEPRINT & CRAFTING",
];

/// The box before a blueprint the player has, and before one he lacks.
pub const BOX_HAVE: &str = "<EM4>[x]</EM4>";
pub const BOX_MISSING: &str = "[  ]";

fn headings_alternation() -> String {
    HEADINGS.iter().map(|h| regex::escape(h)).collect::<Vec<_>>().join("|")
}

fn compile(pattern: &str) -> Regex {
    Regex::new(pattern).unwrap_or_else(|e| panic!("pattern {pattern}: {e}"))
}

/// `injection.MARK`.
pub static MARK: LazyLock<Regex> =
    LazyLock::new(|| compile(&format!("{}.*?{}", regex::escape(OPEN), regex::escape(CLOSE))));

/// `injection.COUNTING_TITLE`: a title form only this tool wrote.
pub static COUNTING_TITLE: LazyLock<Regex> =
    LazyLock::new(|| compile(&format!(r"<EM4>\[(?:BP|Bauplan)(?:{PY_SPACE}+\d+/\d+|!)\]</EM4>")));

/// `injection.TITLE_MARK`: a blueprint mark at a title, by whoever.
pub static TITLE_MARK: LazyLock<Regex> = LazyLock::new(|| compile(r"<EM4>[^<>]*\[(?:BP|Bauplan)[^\]]*\][^<>]*</EM4>"));

/// `injection.OWN_TRACE`.
pub static OWN_TRACE: LazyLock<Regex> = LazyLock::new(|| compile(&headings_alternation()));

fn block_tail() -> String {
    format!(r"(?:\\n){{1,2}}?{PY_SPACE}*-{{20,}}(?:\\n|{PY_SPACE}|<EM\d>)*(?:{}).*$", headings_alternation())
}

/// `injection.UNMARKED_BLOCK`: a block without the title addition.
pub static UNMARKED_BLOCK: LazyLock<Regex> = LazyLock::new(|| compile(&format!("(?s){}", block_tail())));

/// `injection.UNMARKED`: the title addition or a block, without marks.
pub static UNMARKED: LazyLock<Regex> = LazyLock::new(|| {
    compile(&format!(
        r"(?s)(?:{s}*<EM4>\[(?:BP|Bauplan)(?:{s}+\d+/\d+)?!?(?: [\d.,]+ Rep)?\]</EM4>{s}*$|{tail})",
        s = PY_SPACE,
        tail = block_tail()
    ))
});

/// `injection.FOREIGN_APPENDIX`: where a block of another tool begins.
pub static FOREIGN_APPENDIX: LazyLock<Regex> = LazyLock::new(|| {
    compile(&format!(
        concat!(
            r"(?:\\n{s}*){{2}}(?:",
            r"-{{3,20}}{s}*[A-Za-z][A-Za-z ]{{1,30}}{s}*-{{3,20}}",
            r"|={{2,20}}{s}*[A-Za-z][A-Za-z ]{{1,30}}{s}*={{2,20}}",
            r"|<EM\d>{s}*(?:={{2,20}}{s}*)?[A-Za-z][A-Za-z ]{{1,30}}",
            r"(?:{s}*={{2,20}})?{s}*</EM\d>",
            r")"
        ),
        s = PY_SPACE
    ))
});

/// `injection.FOREIGN_TAG`: a tag at the start of a name (`[CS1] …`).
pub static FOREIGN_TAG: LazyLock<Regex> =
    LazyLock::new(|| compile(&format!(r"^\[[A-Za-z0-9/. -]{{1,14}}\]{PY_SPACE}")));

/// Which fallback may cut an addition out by its form alone.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Fallback {
    /// None (a fresh file, or stored original texts).
    Off,
    /// Only the block, never the title (`UNMARKED_BLOCK`).
    Block,
    /// Title addition and block (`UNMARKED`).
    Full,
}

impl Fallback {
    fn pattern(self) -> Option<&'static Regex> {
        match self {
            Fallback::Off => None,
            Fallback::Block => Some(&UNMARKED_BLOCK),
            Fallback::Full => Some(&UNMARKED),
        }
    }
}

/// `injection._has_box`: does this piece hold a box of ours?
pub fn has_box(text: &str) -> bool {
    text.contains("[x]") || text.contains(BOX_MISSING)
}

/// `injection._has_title_mark`.
pub fn has_title_mark(text: &str) -> bool {
    TITLE_MARK.is_match(text)
}

/// `injection._append_block`: our block before a foreign appendix.
pub fn append_block(base: &str, block: &str) -> String {
    match FOREIGN_APPENDIX.find(base) {
        None => format!("{base}{block}"),
        Some(hit) => format!("{}{block}{}", &base[..hit.start()], &base[hit.start()..]),
    }
}

/// `injection._split_foreign_block`: the text without a foreign block of
/// the same source (our heading, no boxes), and that block.
pub fn split_foreign_block(text: &str) -> (String, String) {
    if let Some(hit) = UNMARKED_BLOCK.find(text)
        && !has_box(&text[hit.start()..])
    {
        return (py_rstrip(&text[..hit.start()]).to_string(), text[hit.start()..].to_string());
    }
    (text.to_string(), String::new())
}

/// `injection._strip_old` without the stored original text (that step is
/// the caller's): the old marks, then the form.
pub fn strip_form(text: &str, fallback: Fallback) -> String {
    if text.contains(OPEN) {
        return py_rstrip(&MARK.replace_all(text, "")).to_string();
    }
    let Some(pattern) = fallback.pattern() else { return text.to_string() };
    let Some(hit) = pattern.find(text) else { return text.to_string() };
    let drop = &text[hit.start()..];
    // A block with our heading but without boxes belongs to the player.
    if OWN_TRACE.is_match(drop) && !has_box(drop) {
        return text.to_string();
    }
    let rest = FOREIGN_APPENDIX.find(drop).map_or("", |foreign| &drop[foreign.start()..]);
    format!("{}{rest}", py_rstrip(&text[..hit.start()]))
}

/// `injection._split_line`: `KEY,P=Text` as key, suffix (`,P`) and text.
pub fn split_line(line: &str) -> Option<(&str, &str, &str)> {
    let sep = line.find('=')?;
    if sep < 1 {
        return None;
    }
    let (head, text) = (&line[..sep], &line[sep + 1..]);
    match head.find(',') {
        Some(comma) => Some((&head[..comma], &head[comma..], text)),
        None => Some((head, "", text)),
    }
}

/// `injection._single_line`: line break characters inside a value become a
/// space; the sequence `\n` the game breaks at stays.
pub fn single_line(line: &str) -> String {
    line.chars()
        .map(|c| match c {
            '\n' | '\u{0b}' | '\u{0c}' | '\r' | '\u{1c}' | '\u{1d}' | '\u{1e}' | '\u{85}' | '\u{2028}' | '\u{2029}' => {
                ' '
            }
            c => c,
        })
        .collect()
}

/// `injection._stem`: the beginning a contract's title and descriptions
/// share, lower case; empty when there is none.
pub fn stem(key: &str) -> String {
    let lowered = key.to_lowercase();
    for sep in ["_title", "_desc"] {
        if let Some(pos) = lowered.find(sep)
            && pos > 0
        {
            return lowered[..pos].to_string();
        }
    }
    String::new()
}

/// `injection._name_with_detail`.
pub fn name_with_detail(text: &str, tag: &str) -> String {
    if FOREIGN_TAG.is_match(text) {
        return text.to_string();
    }
    format!("{} {tag}", py_rstrip(&super::specs::strip_tag(text)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn split_line_like_python() {
        assert_eq!(split_line("A,P=x=y"), Some(("A", ",P", "x=y")));
        assert_eq!(split_line("A=x"), Some(("A", "", "x")));
        assert_eq!(split_line("=x"), None);
        assert_eq!(split_line("no"), None);
        assert_eq!(split_line("A,P,Q="), Some(("A", ",P,Q", "")));
    }

    #[test]
    fn stem_cuts_at_title_or_desc() {
        assert_eq!(stem("Covalex_HaulCargo_AToB_title"), "covalex_haulcargo_atob");
        assert_eq!(stem("Covalex_HaulCargo_AtoB_desc_ToRuin"), "covalex_haulcargo_atob");
        assert_eq!(stem("_title"), "");
        assert_eq!(stem("plain"), "");
    }

    #[test]
    fn block_of_the_same_source_without_boxes_stays() {
        let text = format!("CIG text\\n\\n{}\\nBAUPLÄNE AUS DIESEM AUFTRAG\\n    - Atzkav", "-".repeat(57));
        assert_eq!(strip_form(&text, Fallback::Full), text);
        let ours = format!(
            "CIG text\\n\\n{}\\n\\n<EM4>MÖGLICHE BAUPLÄNE FÜR DIESEN MISSIONSTYP</EM4>\\n   [  ] A",
            "-".repeat(57)
        );
        assert_eq!(strip_form(&ours, Fallback::Full), "CIG text");
        assert_eq!(strip_form(&ours, Fallback::Off), ours);
    }

    #[test]
    fn title_marks_are_cut_only_with_the_full_fallback() {
        assert_eq!(strip_form("Title <EM4>[BP 10.000 Rep]</EM4>", Fallback::Full), "Title");
        assert_eq!(strip_form("Title <EM4>[BP]</EM4>", Fallback::Block), "Title <EM4>[BP]</EM4>");
        assert_eq!(strip_form("Title [SCBPW] x [/SCBPW]  ", Fallback::Off), "Title");
    }

    #[test]
    fn our_block_goes_before_a_foreign_appendix() {
        assert_eq!(append_block("Text\\n\\n--- STATS ---\\nA", "\\nB"), "Text\\nB\\n\\n--- STATS ---\\nA");
        assert_eq!(append_block("Text", "\\nB"), "Text\\nB");
    }

    #[test]
    fn line_breaks_in_values_become_spaces() {
        assert_eq!(single_line("a\nb\u{2028}c\\nd"), "a b c\\nd");
    }
}
